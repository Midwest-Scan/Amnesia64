#[derive(Clone, Copy, Debug)]
pub struct HplPreprocessHost {
    pub ctx: *mut c_void,
    /// `GetVar`: pointer to the value (`*len` set to its length), or null if
    /// the variable does not exist. The value must stay valid until the next
    /// `define` call.
    pub get_var: Option<unsafe extern "C" fn(ctx: *mut c_void, name: HplStr, len: *mut usize) -> *const u8>,
    /// `@define`: add a parsing variable.
    pub define: Option<unsafe extern "C" fn(ctx: *mut c_void, name: HplStr, value: HplStr)>,
    /// `@include`: give the file's contents to `out` and return true, or
    /// return false if the file does not exist.
    pub read_include: Option<unsafe extern "C" fn(ctx: *mut c_void, path: HplWStr, out: HplStrOut) -> bool>,
}

fn str_of(b: &[u8]) -> HplStr {
    HplStr { ptr: b.as_ptr(), len: b.len() }
}

unsafe extern "C" fn append_to_vec(ctx: *mut c_void, data: *const u8, len: usize) {
    let v = unsafe { &mut *(ctx as *mut Vec<u8>) };
    v.extend_from_slice(unsafe { raw_slice(data, len) });
}

impl PreprocessHost for HplPreprocessHost {
    fn get_var(&self, name: &[u8]) -> Option<&[u8]> {
        let f = self.get_var?;
        let mut len = 0usize;
        let p = unsafe { f(self.ctx, str_of(name), &mut len) };
        if p.is_null() { None } else { Some(unsafe { std::slice::from_raw_parts(p, len) }) }
    }

    fn define(&mut self, name: &[u8], value: &[u8]) {
        if let Some(f) = self.define {
            unsafe { f(self.ctx, str_of(name), str_of(value)) };
        }
    }

    fn read_include(&mut self, path: &[HplWChar]) -> Option<Vec<u8>> {
        let f = self.read_include?;
        let mut data = Vec::new();
        let out = HplStrOut { sink: Some(append_to_vec), ctx: &mut data as *mut Vec<u8> as *mut c_void };
        let found = unsafe { f(self.ctx, HplWStr { ptr: path.as_ptr(), len: path.len() }, out) };
        found.then_some(data)
    }
}

/// `cPreprocessParser::Parse`: the processed text goes to `output` in one
/// call, also when parsing fails (the C++ appends as it goes).
#[unsafe(no_mangle)]
pub unsafe extern "C" fn hpl_preprocess_parse(input: HplStr, dir: HplWStr, host: *const HplPreprocessHost, output: HplStrOut) -> bool {
    let mut host = unsafe { host.read() };
    let mut text = Vec::new();
    let ok = preprocess::parse(unsafe { input.get() }, &mut text, unsafe { dir.get() }, &mut host);
    unsafe { output.put(&text) };
    ok
}
