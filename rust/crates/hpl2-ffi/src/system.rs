use std::ffi::c_void;

/// The platform's `wchar_t` (declared as `typedef wchar_t HplWChar;` in the
/// generated header).
pub type HplWChar = hpl_system::WChar;

// ---------------------------------------------------------------------------
// String views and sinks
// ---------------------------------------------------------------------------

/// A narrow string (`tString` / `const char*`) by pointer and length.
/// A null `ptr` stands for a null `const char*` where the C++ accepts one.
#[repr(C)]
#[derive(Clone, Copy, Debug)]
pub struct HplStr {
    pub ptr: *const u8,
    pub len: usize,
}

/// A wide string (`tWString`) by pointer and length.
#[repr(C)]
#[derive(Clone, Copy, Debug)]
pub struct HplWStr {
    pub ptr: *const HplWChar,
    pub len: usize,
}

impl HplStr {
    /// # Safety
    /// `ptr` must be null or valid for `len` bytes during `'a`.
    unsafe fn get<'a>(self) -> &'a [u8] {
        unsafe { raw_slice(self.ptr, self.len) }
    }

    /// `None` for a null pointer.
    unsafe fn opt<'a>(self) -> Option<&'a [u8]> {
        if self.ptr.is_null() { None } else { Some(unsafe { self.get() }) }
    }
}

impl HplWStr {
    unsafe fn get<'a>(self) -> &'a [HplWChar] {
        unsafe { raw_slice(self.ptr, self.len) }
    }

    unsafe fn opt<'a>(self) -> Option<&'a [HplWChar]> {
        if self.ptr.is_null() { None } else { Some(unsafe { self.get() }) }
    }
}

// The sink types are written out (not generated by a macro) so cbindgen
// sees them.

/// Receives narrow text.
pub type HplStrSink = Option<unsafe extern "C" fn(ctx: *mut c_void, data: *const u8, len: usize)>;

/// Receives narrow text: a sink and its context.
#[repr(C)]
#[derive(Clone, Copy, Debug)]
pub struct HplStrOut {
    pub sink: HplStrSink,
    pub ctx: *mut c_void,
}

impl HplStrOut {
    /// Hand `data` to the sink (no-op for a null sink).
    unsafe fn put(self, data: &[u8]) {
        if let Some(f) = self.sink {
            unsafe { f(self.ctx, data.as_ptr(), data.len()) };
        }
    }
}

