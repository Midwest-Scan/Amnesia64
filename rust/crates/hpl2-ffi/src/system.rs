//! `cString` and `cPreprocessParser` (`HPL2/core/*/system`).
//!
//! Strings cross the boundary as views ([`HplStr`], [`HplWStr`]: pointer +
//! length, so embedded NULs survive) and come back through output sinks
//! ([`HplStrOut`], ...): a C callback plus a context pointer. The C++ side
//! decides what a sink does with the data (assign to a `tString`, append,
//! push into a vector), so Rust never allocates memory that C++ must free.
//! See `RsStr`, `RsAssign`, `RsPush`, ... in `RustBridge.h`.

#![allow(clippy::missing_safety_doc)]

