/// `EncodeDataToTextString`: the sink is not called if `size` is not a
/// multiple of 4 (the C++ then leaves the output string untouched).
#[unsafe(no_mangle)]
pub unsafe extern "C" fn hpl_string_encode_data_to_text_string(data: *const u8, size: usize, out: HplStrOut) {
    if let Some(text) = s::encode_data_to_text_string(unsafe { raw_slice(data, size) }) {
        unsafe { out.put(&text) };
    }
}

#[unsafe(no_mangle)]
pub unsafe extern "C" fn hpl_string_decode_data_from_text_string(text: HplStr, dest: *mut u8, size: usize) {
    if dest.is_null() || size == 0 {
        return;
    }
    let dest = unsafe { std::slice::from_raw_parts_mut(dest, size) };
    s::decode_data_from_text_string(unsafe { text.get() }, dest);
}

