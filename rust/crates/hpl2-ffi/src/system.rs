/// `GetStringVec`: the sink receives each part in turn. A null `separators`
/// means the default set.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn hpl_string_get_string_vec(a: HplStr, separators: HplStr, out: HplStrOut) {
    for part in s::get_string_vec(unsafe { a.get() }, unsafe { separators.opt() }, Separators::WithCr) {
        unsafe { out.put(&part) };
    }
}

/// `GetStringVecW` (`without_cr` false) and `GetStringWVec` (true, whose
/// default separators do not include '\r').
#[unsafe(no_mangle)]
pub unsafe extern "C" fn hpl_string_get_string_vec_w(a: HplWStr, separators: HplWStr, without_cr: bool, out: HplWStrOut) {
    let defaults = if without_cr { Separators::WithoutCr } else { Separators::WithCr };
    for part in s::get_string_vec(unsafe { a.get() }, unsafe { separators.opt() }, defaults) {
        unsafe { out.put(&part) };
    }
}

