/// `UIntStringToArray`: writes up to `size` values; returns how many.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn hpl_string_uint_string_to_array(dest: *mut u32, a: HplStr, size: i32) -> i32 {
    let values = s::uint_string_to_array(unsafe { a.get() }, size.max(0) as usize);
    for (i, v) in values.iter().enumerate() {
        unsafe { dest.add(i).write(*v) };
    }
    values.len() as i32
}

